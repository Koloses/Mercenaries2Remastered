"""third_party/smaa -> dll/src/smaa_data.h (HLSL source as a C string, area/search lookup textures as bytes)."""
import os, re
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
S = os.path.join(R, 'third_party', 'smaa')
def arr(path, name):
    t = open(os.path.join(S, path)).read()
    body = t[t.index('{', t.index(name)) + 1:t.index('};', t.index(name))]
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', body)]
area = arr('AreaTex.h', 'areaTexBytes'); search = arr('SearchTex.h', 'searchTexBytes')
assert len(area) == 160 * 560 * 2 and len(search) == 64 * 16, (len(area), len(search))
src = open(os.path.join(S, 'SMAA.hlsl'), encoding='latin1').read().encode('ascii', 'replace').decode()
out = ['/* generated by tools/gen_smaa.py from third_party/smaa (SMAA, MIT license) - do not edit */', '#pragma once']
out.append('static const char g_smaaHlsl[] =')
for line in src.split('\n'):
    out.append('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
out.append(';')
def carr(name, data):
    out.append('static const unsigned char %s[%d] = {' % (name, len(data)))
    for i in range(0, len(data), 40): out.append(','.join(str(b) for b in data[i:i + 40]) + ',')
    out.append('};')
carr('g_smaaArea', area); carr('g_smaaSearch', search)
open(os.path.join(R, 'dll', 'src', 'smaa_data.h'), 'w').write('\n'.join(out) + '\n')
print('ok', len(area), len(search), len(src))
